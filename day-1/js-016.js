/* IIFE stands for immediately invoked function expresstion. It is a function expression that executes imediately after it is
defined. We typically wrap the function in parentheses and add another pair of parentheses to invoke it. IIFE were commonly
used to create private scopes, avoid global namespace pollution, and encapsulate variable using closures. Although 
ES modules and block-scoped variables have reduced the need for IIFE, they are still useful for one-time initialization 
and understanding older js pattern
*/

